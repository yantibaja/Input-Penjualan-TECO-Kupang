-- Row Level Security
alter table public.products      enable row level security;
alter table public.daily_reports enable row level security;

drop policy if exists "products read"   on public.products;
drop policy if exists "products insert" on public.products;
drop policy if exists "products update" on public.products;
drop policy if exists "products delete" on public.products;
drop policy if exists "reports read"    on public.daily_reports;
drop policy if exists "reports insert"  on public.daily_reports;
drop policy if exists "reports update"  on public.daily_reports;

create policy "products read"   on public.products for select to anon using (true);
create policy "products insert" on public.products for insert to anon with check (true);
create policy "products update" on public.products for update to anon using (true) with check (true);
create policy "products delete" on public.products for delete to anon using (true);
create policy "reports read"   on public.daily_reports for select to anon using (true);
create policy "reports insert" on public.daily_reports for insert to anon with check (true);
create policy "reports update" on public.daily_reports for update to anon using (true) with check (true);

