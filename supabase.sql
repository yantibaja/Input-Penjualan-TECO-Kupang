-- Jalankan di Supabase: SQL Editor -> New query -> Run

create table if not exists public.products (
  id    bigint generated by default as identity primary key,
  name  text not null unique,
  price integer not null default 0,
  sort  integer not null default 0
);

create table if not exists public.daily_reports (
  tanggal            date primary key,
  items              jsonb not null default '[]',
  cash               jsonb not null default '[]',
  qris               jsonb not null default '[]',
  pengeluaran        jsonb not null default '[]',
  total_terjual_uang numeric not null default 0,
  total_cash         numeric not null default 0,
  total_qris         numeric not null default 0,
  total_pengeluaran  numeric not null default 0,
  selisih            numeric not null default 0,
  minus_rill         numeric,
  updated_at        timestamptz not null default now()
);

